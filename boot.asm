; =====================================
; 我的第一个微型引导扇区 (Bootloader)
; =====================================

[org 0x7c00]          ; 告诉汇编器：等会儿 BIOS 会把这段代码加载到内存 0x7c00 处

    mov ah, 0x0e      ; 0x0e 是 BIOS 的“电传打字机”模式（Teletype），用来在屏幕上打印字符
    mov al, 'H'       ; 我们想打印字母 'H'
    int 0x10          ; 调用 BIOS 的 0x10 号中断（显卡/屏幕相关的中断服务）

    mov al, 'i'       ; 再打印一个 'i'
    int 0x10

    jmp $             ; $ 表示当前行，jmp $ 意思就是跳到自己这里，也就是死循环
                      ; 如果不写这句，CPU 会继续往后读内存里的随机垃圾数据，导致虚拟机崩溃重启

; 引导扇区硬性规定：总大小必须是 512 字节，且最后两个字节必须是 0x55AA
times 510 - ($ - $$) db 0   ; 填充前面的空位为 0（$$ 表示本段的起始地址）
dw 0xaa55                   ; 魔数：最后两字节（注意因为小端序，在二进制编辑器里会显示为 55 aa）
